"""
Writes src/theme/themes.css: for each non-default theme, the replacement of every
accent colour used in the app's CSS (`--tc-*` hex and `--tr-*` rgb variables).
Run from drawary-v2/:  python3 scripts/make_theme_css.py
Re-run after adding a new accent colour (src/flow/themeColors.test.ts fails until you do).
The default theme (lavender) defines nothing: the fallbacks in the CSS are the
approved colours.
"""
import glob, re, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from theme_colors import THEMES, TINT_RGB, shift

hexes, rgbs = set(), set()
for f in glob.glob('src/**/*.css', recursive=True):
    if f.endswith('themes.css'): continue
    s = open(f).read()
    hexes |= set(re.findall(r'--tc-([0-9a-f]{6})\b', s))
    rgbs |= set(re.findall(r'--tr-(\d+)-(\d+)-(\d+)\b', s))

# Roots whose own cream background would hide the themed page background. Found by scanning the CSS:
# single-class rules named *-screen / *-page / app shell with a cream (or cream variable) background.
ROOTS = [
    'drawary-app-shell', 'al43-screen', 'bkd46-screen', 'bks48-screen', 'bkt45-screen', 'cc-screen', 'dmh44-screen',
    'drc53-screen', 'dd-screen', 'df-screen', 'drawary-field-screen', 'faq56-screen', 'fb59-screen', 'fd-screen',
    'guide57-screen', 'help55-screen', 'info58-screen', 'lang54-screen', 'ld41-screen', 'nic-page', 'nf-screen',
    'nc-screen', 'ndf-screen', 'ns-screen', 'nt-screen', 'ps42-screen', 'rd-screen', 're-screen', 'rcx-screen',
    'rc-screen', 'red-screen', 'rm-screen', 'rtd-screen', 'rfp49-screen', 'rp51-screen', 'rr50-screen', 'rs52-screen',
    'sec40-screen', 'tv-screen', 'ts39-screen', 'dm-screen', 'ncs-screen', 'settings-home-screen', 'stats-screen', 'hs-screen',
    'global-search-screen',
]
BASE = 'linear-gradient(180deg,#fffaf2 0%,#fffdf8 52%,#fdf9f2 100%)'

out = ['/* GENERATED by scripts/make_theme_css.py -- do not edit by hand. */\n']
# Lavender (the default) has the same page background, with its own main colour as the tint.
r, g, b = TINT_RGB['lavender']
out.append(f':root{{--theme-bg:radial-gradient(circle at 18% 7%,rgba({r},{g},{b},.08),transparent 34%),{BASE};}}\n')
def decls(theme):
    r, g, b = TINT_RGB[theme]
    d = [f'--theme-bg:radial-gradient(circle at 18% 7%,rgba({r},{g},{b},.08),transparent 34%),{BASE};']
    for h in sorted(hexes):
        r, g, b = shift(int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), theme)
        d.append(f'--tc-{h}:#{r:02x}{g:02x}{b:02x};')
    for (r, g, b) in sorted(rgbs, key=lambda t: tuple(map(int, t))):
        r2, g2, b2 = shift(int(r), int(g), int(b), theme)
        d.append(f'--tr-{r}-{g}-{b}:{r2},{g2},{b2};')
    return d

for theme in THEMES:
    out.append(f':root[data-color-theme="{theme}"]{{')
    out.extend(decls(theme))
    out.append('}')
    # the one picture used as a CSS background (#08's dimmed home)
    out.append(f':root[data-color-theme="{theme}"] .drawary-app-shell[data-route="create-drawer"] .drawary-dimmed-home::after{{background-image:url("/assets-theme/{theme}/ui-icons/icon_flower.webp")}}\n')
# The same colours on any element marked data-preview-theme (the live preview in the theme settings shows the real home screen in
# each theme). Lavender, the default, has no page-level block, so its preview lists the approved colours explicitly.
out.append('/* data-preview-theme: a piece of the page drawn in another theme than the page itself. */')
for theme in THEMES:
    out.append(f'[data-preview-theme="{theme}"]{{')
    out.extend(decls(theme))
    out.append('}')
out.append('[data-preview-theme="lavender"]{')
r, g, b = TINT_RGB['lavender']
out.append(f'--theme-bg:radial-gradient(circle at 18% 7%,rgba({r},{g},{b},.08),transparent 34%),{BASE};')
for h in sorted(hexes): out.append(f'--tc-{h}:#{h};')
for (r, g, b) in sorted(rgbs, key=lambda t: tuple(map(int, t))): out.append(f'--tr-{r}-{g}-{b}:{r},{g},{b};')
out.append('}')
out.append('/* The themed page background (DRAWARY_THEME_GRADIENT_SPEC): the screens above go transparent so it shows. */')
sel = ',\n'.join(f':root .{c}' for c in ROOTS)
out.append(sel + '{background:transparent!important}')
out.append(':root body::before{content:"";position:fixed;inset:0;z-index:-1;pointer-events:none;background:var(--theme-bg)}')
open('src/theme/themes.css', 'w').write('\n'.join(out))
print(len(hexes), 'hex +', len(rgbs), 'rgb colours x', len(THEMES), 'themes')
